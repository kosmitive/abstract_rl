"""Parity of the MLX port with the PyTorch implementation of eb41282.

The fixture ``golden/torch_eb41282.npz`` is generated by ``golden/generate_golden.py`` from the PyTorch code. The
parameters stored there are loaded into the MLX modules, the same computation is run on the same inputs and the
outputs are compared. The tests run on the CPU in float32 (the temperature dual in float64).
"""


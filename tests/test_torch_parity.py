GOLDEN = np.load(Path(__file__).parent / "golden" / "torch_eb41282.npz")


def _load(module: Any, prefix: str) -> None:
    items = [(k[len(prefix) + 1 :], mx.array(GOLDEN[k])) for k in GOLDEN.files if k.startswith(prefix + "/")]
    assert items
    module.update(tree_unflatten(items))


def _assert_params(module: Any, prefix: str, rtol: float = 1e-5, atol: float = 1e-6) -> None:
    got = dict(tree_flatten(module.trainable_parameters()))
    expected = {k[len(prefix) + 1 :]: GOLDEN[k] for k in GOLDEN.files if k.startswith(prefix + "/")}
    assert set(got) == set(expected)
    for k, v in expected.items():
        np.testing.assert_allclose(np.array(got[k]), v, rtol=rtol, atol=atol, err_msg=k)


def _mc(base: dict[str, Any], alg: str, root: Path) -> ModelConfiguration:
    conf = copy.deepcopy(base)
    conf.update({"alg": alg, "data_root": str(root)})
    mc = ModelConfiguration(conf)
    mc.add_main("log", DataLogger(mc.data_dir))
    with mc["conf"].ns("env"):
        mc.add_environment(RolloutEnvWrapper(mc))
    return mc


def _trajectory(prefix: str, env: Any) -> Any:
    s, a, r, ll, d = (GOLDEN[f"{prefix}/{k}"] for k in ("s", "a", "r", "ll", "d"))
    builder = TrajectoryBuilder(0, env, s[0].astype(np.float64))
    for t in range(len(a)):
        builder.observe(
            a[t].astype(np.float64), float(r[t, 0]), s[t + 1].astype(np.float64), float(ll[t, 0]), int(d[t, 0])
        )
    return builder.finalize()


def _batch(s: np.ndarray, a: np.ndarray, ll: np.ndarray, annotations: dict[str, np.ndarray]) -> Batch:
    n = len(s)
    return Batch(s, a, ll, np.zeros((n, 1), np.float32), s, np.zeros((n, 1), np.float32), annotations)


def build_trpo(root: Path) -> ModelConfiguration:
    """TRPO model configuration with the policy and the value network of the fixture."""
    mc = _mc(trpo_config, "trpo", root)
    conf = mc["conf"]
    with conf.ns("policy"):
        policy = select_policy(mc)
        mc.add_syncable("policy", policy, 1)
    with conf.ns("val"):
        v_net = FullyVNeuralNet(mc)
        mc.add_syncable("v_network", v_net, 1)
    _load(policy, "trpo/policy")
    _load(mc.get("policy", True), "trpo/policy")
    _load(v_net.net, "trpo/v")
    _load(mc.get("v_network", True).net, "trpo/v")
    return mc


def build_mpo(root: Path) -> ModelConfiguration:
    """MPO model configuration with the policy and the Q network of the fixture."""
    mc = _mc(mpo_config, "mpo", root)
    conf = mc["conf"]
    with conf.ns("policy"):
        policy = select_policy(mc)
        mc.add_syncable("policy", policy, 1)
    with conf.ns("val"):
        q_net = FullyQNeuralNet(mc)
        mc.add_syncable("q_network", q_net, 1)
    _load(policy, "mpo/policy")
    _load(mc.get("policy", True), "mpo/policy")
    _load(q_net.fc_net, "mpo/q")
    _load(mc.get("q_network", True).fc_net, "mpo/q")
    return mc


def trpo_batch() -> Batch:
    return _batch(GOLDEN["trpo/s"], GOLDEN["trpo/act"], GOLDEN["trpo/ll"], {"a": GOLDEN["trpo/adv"]})


@pytest.fixture
def trpo(tmp_path):
    return build_trpo(tmp_path)


@pytest.fixture
def mpo(tmp_path):
    return build_mpo(tmp_path)


def test_policy_forward_log_prob_and_mode(trpo):
    policy = trpo.get("policy", False)
    s = mx.array(GOLDEN["trpo/s"])
    np.testing.assert_allclose(np.array(policy.forward(s)), GOLDEN["trpo/stats"], rtol=1e-5, atol=1e-6)
    ll = policy.log_prob(mx.array(GOLDEN["trpo/act"]), states=s)
    np.testing.assert_allclose(np.array(ll), GOLDEN["trpo/ll"], rtol=1e-5, atol=1e-5)
    np.testing.assert_allclose(np.array(policy.mode(states=s)), GOLDEN["trpo/mode"], rtol=1e-5, atol=1e-6)


def test_kl_divergence(trpo):
    policy = trpo.get("policy", False)
    _load(trpo.get("policy", True), "trpo/policy_perturbed")
    batch = _batch(GOLDEN["trpo/s"], GOLDEN["trpo/act"], GOLDEN["trpo/ll"], {})
    kl_m = policy.kl_divergence(batch, mode="m-projection", est="mean").item()
    kl_i = policy.kl_divergence(batch, mode="i-projection", est="sum").item()
    np.testing.assert_allclose(kl_m, GOLDEN["trpo/kl_m_mean"], rtol=1e-4)
    np.testing.assert_allclose(kl_i, GOLDEN["trpo/kl_i_sum"], rtol=1e-4)


def test_conjugate_gradient():
    a, b = mx.array(GOLDEN["cg/a"]), mx.array(GOLDEN["cg/b"])
    x = conjugate_gradient(lambda v: a @ v, b, 10, 1e-10)
    np.testing.assert_allclose(np.array(x), GOLDEN["cg/x"], rtol=1e-4, atol=1e-5)


def test_trpo_step(trpo):
    with trpo["conf"].ns("trpo"):
        alg = TRPOAlgorithm(trpo)
    batch = trpo_batch()
    alg.perform_tr_sgd(0, batch, batch)
    _assert_params(trpo.get("policy", False), "trpo/policy_after_step", rtol=1e-3, atol=1e-5)


def test_value_function_adam_steps(trpo):
    v_net = trpo.get("v_network", False)
    s, tv = GOLDEN["v/s"], GOLDEN["v/tv"]
    a = np.zeros((len(s), 1), np.float32)
    for k in range(5):
        v_net.perform_adam_step(k, _batch(s, a, a, {"tv": tv}))
    _assert_params(v_net.net, "trpo/v_after_adam", rtol=1e-4, atol=1e-6)


@pytest.mark.parametrize("name", ["traj_trunc", "traj_done"])
def test_td_and_gae(trpo, name):
    with trpo["conf"].ns("tdop"):
        td_op = TemporalDifferenceOperator(trpo)
    with trpo["conf"].ns("gae"):
        gae = GeneralizedAdvantagesEstimationOperator(trpo)
    traj = _trajectory(name, trpo.env)
    td_op.transform_all([traj])
    gae.transform_all([traj])
    for key, golden in (("tv", "tv"), ("td", "td"), ("a", "adv")):
        np.testing.assert_allclose(traj[key], GOLDEN[f"{name}/{golden}"], rtol=1e-5, atol=1e-4, err_msg=key)


@pytest.mark.parametrize("name", ["mtraj_trunc", "mtraj_done"])
def test_retrace(mpo, name):
    with mpo["conf"].ns("ret"):
        ret = RetraceOperator(mpo)
    t_q = mpo.get("q_network", True)

    # the fixture uses the value of the policy mode instead of the sampled estimate
    def v_mode(states, exp_actions=10, policy=None):
        return t_q.q_val(states, policy.mode(states=states))

    object.__setattr__(t_q, "v_val", v_mode)
    traj = _trajectory(name, mpo.env)
    ret.transform(traj)
    materialize([traj])
    np.testing.assert_allclose(traj["q"], GOLDEN[f"{name}/q"], rtol=1e-5, atol=1e-5)
    np.testing.assert_allclose(traj["tq"], GOLDEN[f"{name}/tq"], rtol=1e-5, atol=1e-4)


def test_temperature_dual():
    eta = find_optimal_temperature(mx.array(GOLDEN["dual/q"]), 0.05, 1.0, 0.05)
    np.testing.assert_allclose(np.array(eta), GOLDEN["dual/eta"], rtol=1e-5)


def test_mpo_m_steps(mpo):
    with mpo["conf"].ns("mpo"):
        alg = MPOAlgorithm(mpo)
    s, add_act = GOLDEN["mstep/s"], GOLDEN["mstep/add_act"]
    batch = _batch(
        s, add_act[:, :1], GOLDEN["mstep/ll"], {"add_act": add_act, "grad_ranking": GOLDEN["mstep/grad_ranking"]}
    )
    for k in range(3):
        alg.perform_step(k, batch)
    _assert_params(mpo.get("policy", False), "mpo/policy_after_mstep", rtol=1e-4, atol=1e-6)
    lm = np.concatenate([np.array(v) for v in alg.lagrange_mults])
    np.testing.assert_allclose(lm, GOLDEN["mstep/lm"], rtol=1e-5, atol=1e-6)


def test_q_function_adam_steps(mpo):
    q_net = mpo.get("q_network", False)
    s, a, tq = GOLDEN["qfit/s"], GOLDEN["qfit/a"], GOLDEN["qfit/tq"]
    for k in range(3):
        q_net.perform_adam_step(k, _batch(s, a, a, {"tq": tq}))
    # adam normalizes the step, for weights with a gradient close to zero rounding differences reach a fraction of lr
    _assert_params(q_net.fc_net, "mpo/q_after_adam", rtol=1e-4, atol=1e-4)
